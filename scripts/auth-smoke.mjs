import assert from 'node:assert/strict';
const base=process.env.MUSE_TEST_URL??'http://127.0.0.1:5173';
if(new URL(base).hostname!=='127.0.0.1')throw Error('Synthetic identity checks are local-only.');
if(!process.env.GK_TEST_PASSWORD)throw Error('Set the temporary local GK_TEST_PASSWORD.');
const request=(path,options={})=>fetch(base+path,{signal:AbortSignal.timeout(20000),...options});
const headers={'Content-Type':'application/json','X-Real-IP':'local-auth-regression'};
const login=await request('/api/admin/session',{method:'POST',headers,body:JSON.stringify({password:process.env.GK_TEST_PASSWORD})});
assert.equal(login.status,200,'Local password login succeeds');
const cookie=login.headers.getSetCookie()[0].split(';')[0];
assert.equal((await (await request('/api/admin/session',{headers:{Cookie:cookie}})).json()).authenticated,true,'Password session authenticates');
const logout=await request('/api/admin/session',{method:'DELETE',headers:{...headers,Cookie:cookie},body:'{}'});
assert.equal(logout.status,200);
assert.equal((await logout.json()).redirect,'/admin','Password logout returns to login');
const cleared=logout.headers.getSetCookie();
assert.equal(cleared.length,2,'Both admin and Discord cookies are cleared separately');
assert(cleared.every(value=>value.includes('Max-Age=0')));
assert.equal((await (await request('/api/admin/session',{headers:{Cookie:cookie}})).json()).authenticated,false,'Deleted session cannot be reused');
const siteLogin=await request('/signin-with-chatgpt?return_to=%2Fadmin',{redirect:'manual'});
assert.equal(siteLogin.status,302);
const siteCookie=siteLogin.headers.getSetCookie()[0].split(';')[0];
const siteLogout=await request('/api/admin/session',{method:'DELETE',headers:{...headers,Cookie:siteCookie},body:'{}'});
assert.equal(siteLogout.status,200);
assert.equal((await siteLogout.json()).redirect,'/signout-with-chatgpt?return_to=%2Fadmin','Site identity is signed out through the platform');
const platformLogout=await request('/signout-with-chatgpt?return_to=%2Fadmin',{headers:{Cookie:siteCookie},redirect:'manual'});
assert.equal(platformLogout.status,302);
assert(platformLogout.headers.getSetCookie().some(value=>value.includes('Max-Age=0')),'Platform logout clears its own identity cookie');
console.log('PASS password login, session revocation, separate expired cookies, and platform owner logout');
